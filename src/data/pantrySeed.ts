function daysFromToday(offset: number): string {
  const d = new Date();
  d.setHours(12, 0, 0, 0);
  d.setDate(d.getDate() + offset);
  return d.toISOString().slice(0, 10);
}

function id(prefix: string, n: number): string {
  return `${prefix}-${n}`;
}

